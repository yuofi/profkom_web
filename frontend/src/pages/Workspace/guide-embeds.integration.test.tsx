// @vitest-environment jsdom
import axios from "axios";
import { afterEach, expect, it } from "vitest";
import { liveLogin, liveParticipant, livePassword } from "../../test/liveApi";
import { mountWorkspace, waitForPage } from "../../test/workspace";
import { api } from "../../utils/api";
import { materialsApi } from "../../utils/api/materials.api";
import { membershipApi } from "../../utils/api/membership.api";
import { MaterialContent } from "../../components/Workspace/MaterialContent";
import { wireIssues } from "../../test/wireContract";
import { richText } from "../../utils/api/contract";
let page: Awaited<ReturnType<typeof mountWorkspace>> | undefined;
afterEach(async () => { await page?.cleanup();page = undefined; });
it("compiles through real HTTP, publishes only saved valid source, and renders the wire tree without granting a reader draft access", async () => {
  const reader = await liveParticipant("guide-embeds-reader");
  const session = await liveLogin();
  const blocks = await membershipApi.blocks();
  const block = blocks.find(item => item.capabilities.includes("edit_block"))!;
  let m = await materialsApi.create({ kind: "guide", owner_block_id: block.block_id, title: `Оформление ${crypto.randomUUID()}`, description: "Синтетический гайд", content: richText("Старая публикация") });
  expect(m.capabilities).toContain("edit_html_material");
  m = await materialsApi.audience(m.material_id, "everyone", { expected_revision: m.revision });
  m = await materialsApi.publish(m.material_id, { expected_revision: m.revision });
  const source = '## План\n\n```profkom-html id=embed-live\n<section class="guide-card guide-gradient-success"><h3>Готовим встречу</h3><p>Соберите команду.</p><a class="guide-button" href="#section-1">К плану</a></section>\n```';
  const content = { format: "markdown-embeds-v1" as const, body: source };
  const preview = await materialsApi.preview(m.material_id, { expected_revision: m.revision, content });
  expect(wireIssues("MaterialText", preview)).toEqual([]);
  expect(preview.render?.diagnostics).toEqual([]);
  expect((await materialsApi.get(m.material_id)).revision).toBe(m.revision);
  const invalid = await materialsApi.update(m.material_id, { expected_revision: m.revision, content: { ...content, body: source.replace('<p>', '<p onclick="alert(1)">') } });
  expect(invalid.draft_content?.render?.diagnostics.length).toBeGreaterThan(0);
  expect(invalid.published_content?.body).toBe("Старая публикация");
  await expect(materialsApi.publish(m.material_id, { expected_revision: invalid.revision })).rejects.toMatchObject({ status: 422 });
  m = await materialsApi.update(m.material_id, { expected_revision: invalid.revision, content });
  await expect(materialsApi.preview(m.material_id, { expected_revision: invalid.revision, content })).rejects.toMatchObject({ status: 409 });
  m = await materialsApi.publish(m.material_id, { expected_revision: m.revision });
  expect(wireIssues("Material", m)).toEqual([]);
  expect(m.published_content?.body).toBe(source);
  expect(m.published_content?.render?.source_hash).toBe(preview.render?.source_hash);
  const readonly = axios.create({ baseURL: api.defaults.baseURL, timeout: 10000, validateStatus: () => true });
  const login = await readonly.post('/auth/login', { email: reader.email, password: livePassword });expect(login.status).toBe(200);
  readonly.defaults.headers.common.Authorization = `Bearer ${login.data.access_token}`;
  const visible = await readonly.get(`/materials/${m.material_id}`);expect(visible.status).toBe(200);
  expect(visible.data).not.toHaveProperty('source_content');expect(visible.data).not.toHaveProperty('draft_content');
  expect([403, 404]).toContain((await readonly.post(`/materials/${m.material_id}/preview`, { expected_revision: m.revision, content })).status);
  page = await mountWorkspace(<MaterialContent content={visible.data.published_content} materialId={m.material_id} />, { session });
  await waitForPage(page, () => !!page!.container.querySelector('[data-guide-embed]'));
  expect(page.container.textContent).toContain("Готовим встречу");
  expect(page.container.querySelector('a[href$="-section-1"]')).not.toBeNull();
});
